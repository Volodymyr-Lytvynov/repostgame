const STRINGS: Record<Language, Record<string, string>> = { en: EN, ru: RU };

export function t(language: Language, key: string, vars?: Record<string, string | number>): string {
  const template = STRINGS[language][key] ?? STRINGS.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}
